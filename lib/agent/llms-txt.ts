export type LlmsTxtOptions = {
  activeListingCount?: number | null
}

/** Agent guide served at /llms.txt. */
export function buildLlmsTxt(origin: string, options?: LlmsTxtOptions): string {
  const base = origin.replace(/\/$/, "")
  const countLine =
    typeof options?.activeListingCount === "number"
      ? `Live public listings right now: ${options.activeListingCount}.`
      : null

  return [
    "# Reswell",
    "",
    "> Reswell is a peer-to-peer marketplace for physical used surfboards and surf gear (boards, fins, wetsuits, and more).",
    "> Use the public research API below instead of scraping HTML — especially for pricing and search.",
    "",
    `Website: ${base}`,
    `Human docs / try-it: ${base}/public-api`,
    `OpenAPI: ${base}/openapi.json`,
    `Sitemap: ${base}/sitemap.xml`,
    countLine,
    "",
    "## Preferred research flow",
    "",
    "1. Search models (or listings). Filter by brand, model, or city when the question names them.",
    "2. Fetch pricing by brand + model and/or a specific listing by id or slug.",
    "3. Read image_url on search cards and image_urls (up to 8) on listing detail.",
    "4. Link humans to the canonical HTML URLs returned in `urls`.",
    "",
    "## Public research API",
    "",
    "No API key required. CORS open (`Access-Control-Allow-Origin: *`).",
    'Response shape: `{ "success": true, "data": { ... } }`',
    "",
    "### Rate limits",
    "",
    "| Tier | Limit | Auth |",
    "|------|-------|------|",
    "| Free | 10 requests / minute (per IP) | None |",
    "| Registered | 30 requests / minute (per account) | `Authorization: Bearer <auth_token>` from a free Reswell account |",
    "",
    "Over limit → HTTP `429` + `Retry-After`.",
    "",
    "### Search (find a model or listing)",
    `- \`GET ${base}/api/public/search?q={query}&type=models&limit=5\``,
    "- `type`: `models` (default, preferred) or `listings`",
    "- `limit`: 1–10 (default 5). No deep pagination — page 1 only.",
    "- Optional filters: `brand`, `model`, `city` (city applies to listings).",
    "- `q` is optional when at least one filter is set.",
    "- Model cards include `image_url` when the catalog has a photo.",
    "- Listing cards include one `image_url`.",
    "",
    "### Market pricing (brand / model comps / sold prices)",
    `- \`GET ${base}/api/public/pricing?brand={brand}&model={model}\``,
    "- `brand` is required (slug or name). `model` is optional (name or slug).",
    "- Prefer this over crawling `/search` or `/boards` HTML for comps.",
    "- Returns asking + sold min/max/avg/median USD (last 365 days), recent sold comps, and canonical HTML links.",
    "- Each recent sold comp includes `image_url` when the sold listing has a photo.",
    "",
    "### Listing detail (buy a specific copy)",
    `- \`GET ${base}/api/public/listings/{id}\``,
    "- `{id}` may be a listing slug or UUID.",
    `- HTML equivalent: ${base}/l/{id}`,
    "- `image_urls` is the gallery, primary photo first, up to 8 absolute URLs.",
    "- Listing HTML also sends `Link: rel=\"alternate\"` to this JSON URL and `rel=\"describedby\"` to this file.",
    "",
    "### Catalog",
    `- \`GET ${base}/api/public\` — machine-readable endpoint index`,
    `- \`GET ${base}/openapi.json\` — OpenAPI 3.1 specification`,
    "",
    "## Questions people ask",
    "",
    `- Used boards for a brand and model: \`${base}/api/public/search?type=listings&brand={brand}&model={model}&limit=5\``,
    `- Boards in a city: add \`&city={city}\` (example: \`San Diego\`).`,
    `- What a model looks like: \`${base}/api/public/search?type=models&q={model}&brand={brand}\` and read \`image_url\`.`,
    `- Photos of one board: \`${base}/api/public/listings/{id}\` field \`image_urls\`.`,
    "- Categories with their own browse pages: surfboards (`/boards`), fins, wetsuits, boardbags, surfpacks, leashes, apparel, accessories, magazines, traction.",
    "",
    "## Examples",
    "",
    "```",
    `GET ${base}/api/public/search?q=channel+islands+twin+pin&type=models&limit=5`,
    `GET ${base}/api/public/search?type=listings&brand=channel-islands&model=twin-pin&city=San%20Diego&limit=5`,
    `GET ${base}/api/public/pricing?brand=channel-islands&model=twin-pin`,
    `GET ${base}/api/public/listings/{listingId}`,
    "",
    "# Registered tier (30/min)",
    `GET ${base}/api/public/pricing?brand=channel-islands&model=twin-pin`,
    "Authorization: Bearer <auth_token>",
    "```",
    "",
    "## HTML surfaces (optional)",
    "",
    `- Search: ${base}/search?q={query}`,
    `- Boards browse: ${base}/boards`,
    `- Explore: ${base}/explore`,
    `- Brand pages: ${base}/brands/{brandSlug}`,
    `- Recently sold: ${base}/sold`,
    `- Listings: ${base}/l/{slug}`,
    "",
    "## Please do not",
    "",
    "- Hammer HTML `/search` or paginate search results for research",
    "- Scrape `/boards` or `/sold` HTML when the pricing API is available",
    "- Bypass rate limits or ignore `Retry-After`",
    "- Request unbounded result sets (use `limit` ≤ 10)",
    "",
    "## Contact",
    "",
    `${base}/help`,
    "",
  ]
    .filter((line): line is string => line !== null)
    .join("\n")
}
