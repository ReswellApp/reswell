-- Public feature-request and bug board (/feature-requests) plus changelog.
-- Members post, vote, and comment. Staff set status, estimates, and changelog entries.
-- Vote and comment totals are maintained by triggers so clients cannot write them.

CREATE TABLE IF NOT EXISTS public.feature_requests (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  number integer GENERATED BY DEFAULT AS IDENTITY (START WITH 100 INCREMENT BY 1) NOT NULL,
  kind text NOT NULL CHECK (kind IN ('feature', 'bug')),
  title text NOT NULL,
  body text NOT NULL,
  status text NOT NULL DEFAULT 'idea' CHECK (
    status IN ('idea', 'under_review', 'planned', 'in_progress', 'shipped', 'closed')
  ),
  author_id uuid NOT NULL REFERENCES public.profiles (id) ON DELETE CASCADE,
  tags text[] NOT NULL DEFAULT '{}',
  estimated_label text,
  vote_count integer NOT NULL DEFAULT 0 CHECK (vote_count >= 0),
  comment_count integer NOT NULL DEFAULT 0 CHECK (comment_count >= 0),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT feature_requests_number_key UNIQUE (number)
);

CREATE TABLE IF NOT EXISTS public.feature_request_votes (
  request_id uuid NOT NULL REFERENCES public.feature_requests (id) ON DELETE CASCADE,
  user_id uuid NOT NULL REFERENCES public.profiles (id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (request_id, user_id)
);

CREATE TABLE IF NOT EXISTS public.feature_request_comments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  request_id uuid NOT NULL REFERENCES public.feature_requests (id) ON DELETE CASCADE,
  author_id uuid NOT NULL REFERENCES public.profiles (id) ON DELETE CASCADE,
  body text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.feature_request_changelog (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  request_id uuid REFERENCES public.feature_requests (id) ON DELETE SET NULL,
  title text NOT NULL,
  body text NOT NULL,
  published_at timestamptz NOT NULL DEFAULT now(),
  created_by uuid REFERENCES public.profiles (id) ON DELETE SET NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS feature_request_changelog_request_uidx
  ON public.feature_request_changelog (request_id)
  WHERE request_id IS NOT NULL;

CREATE INDEX IF NOT EXISTS feature_requests_open_votes_idx
  ON public.feature_requests (vote_count DESC, created_at DESC)
  WHERE status IN ('idea', 'under_review', 'planned', 'in_progress');

CREATE INDEX IF NOT EXISTS feature_requests_status_votes_idx
  ON public.feature_requests (status, vote_count DESC, created_at DESC);

CREATE INDEX IF NOT EXISTS feature_requests_created_idx
  ON public.feature_requests (created_at DESC);

CREATE INDEX IF NOT EXISTS feature_requests_comment_count_idx
  ON public.feature_requests (comment_count DESC, created_at DESC);

CREATE INDEX IF NOT EXISTS feature_requests_author_created_idx
  ON public.feature_requests (author_id, created_at DESC);

CREATE INDEX IF NOT EXISTS feature_request_comments_request_idx
  ON public.feature_request_comments (request_id, created_at);

CREATE INDEX IF NOT EXISTS feature_request_comments_author_created_idx
  ON public.feature_request_comments (author_id, created_at DESC);

CREATE INDEX IF NOT EXISTS feature_request_changelog_published_idx
  ON public.feature_request_changelog (published_at DESC);

CREATE OR REPLACE FUNCTION public.feature_requests_normalize()
RETURNS trigger
LANGUAGE plpgsql
AS $$
DECLARE
  allowed text[] := ARRAY['buying', 'selling', 'app', 'web', 'offers', 'shipping', 'search'];
  cleaned text[] := '{}';
  tag text;
  staff boolean;
BEGIN
  staff := public.is_admin_or_employee();

  NEW.title := trim(NEW.title);
  NEW.body := trim(NEW.body);

  IF char_length(NEW.title) < 4 OR char_length(NEW.title) > 140 THEN
    RAISE EXCEPTION 'invalid feature request title';
  END IF;
  IF char_length(NEW.body) < 10 OR char_length(NEW.body) > 5000 THEN
    RAISE EXCEPTION 'invalid feature request body';
  END IF;

  IF NEW.estimated_label IS NOT NULL THEN
    NEW.estimated_label := nullif(trim(NEW.estimated_label), '');
    IF NEW.estimated_label IS NOT NULL AND char_length(NEW.estimated_label) > 40 THEN
      RAISE EXCEPTION 'invalid feature request estimate';
    END IF;
  END IF;

  IF NEW.tags IS NULL THEN
    NEW.tags := '{}';
  END IF;
  FOREACH tag IN ARRAY NEW.tags LOOP
    tag := lower(trim(tag));
    IF tag = ANY (allowed) AND NOT tag = ANY (cleaned) THEN
      cleaned := array_append(cleaned, tag);
    END IF;
  END LOOP;
  IF cardinality(cleaned) > 4 THEN
    cleaned := cleaned[1:4];
  END IF;
  NEW.tags := cleaned;

  IF TG_OP = 'INSERT' THEN
    NEW.status := 'idea';
    NEW.estimated_label := NULL;
    NEW.vote_count := 0;
    NEW.comment_count := 0;
    IF NOT staff THEN
      NEW.author_id := auth.uid();
    END IF;
    NEW.updated_at := now();
    RETURN NEW;
  END IF;

  IF current_setting('feature_requests.internal', true) = '1' THEN
    RETURN NEW;
  END IF;

  NEW.author_id := OLD.author_id;
  NEW.number := OLD.number;
  NEW.created_at := OLD.created_at;
  NEW.vote_count := OLD.vote_count;
  NEW.comment_count := OLD.comment_count;
  NEW.updated_at := now();

  IF NOT staff THEN
    NEW.status := OLD.status;
    NEW.kind := OLD.kind;
    NEW.tags := OLD.tags;
    NEW.estimated_label := OLD.estimated_label;
    IF OLD.status IN ('shipped', 'closed') THEN
      NEW.title := OLD.title;
      NEW.body := OLD.body;
    END IF;
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS feature_requests_normalize ON public.feature_requests;
CREATE TRIGGER feature_requests_normalize
  BEFORE INSERT OR UPDATE ON public.feature_requests
  FOR EACH ROW
  EXECUTE FUNCTION public.feature_requests_normalize();

CREATE OR REPLACE FUNCTION public.feature_requests_set_vote_count()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  target uuid := COALESCE(NEW.request_id, OLD.request_id);
BEGIN
  PERFORM set_config('feature_requests.internal', '1', true);
  UPDATE public.feature_requests
  SET vote_count = (
    SELECT count(*)::integer
    FROM public.feature_request_votes v
    WHERE v.request_id = target
  )
  WHERE id = target;
  PERFORM set_config('feature_requests.internal', '', true);
  RETURN COALESCE(NEW, OLD);
END;
$$;

DROP TRIGGER IF EXISTS feature_request_votes_sync_count ON public.feature_request_votes;
CREATE TRIGGER feature_request_votes_sync_count
  AFTER INSERT OR DELETE ON public.feature_request_votes
  FOR EACH ROW
  EXECUTE FUNCTION public.feature_requests_set_vote_count();

CREATE OR REPLACE FUNCTION public.feature_request_comments_normalize()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.body := trim(NEW.body);
  IF char_length(NEW.body) < 1 OR char_length(NEW.body) > 2000 THEN
    RAISE EXCEPTION 'invalid feature request comment';
  END IF;
  IF TG_OP = 'INSERT' AND NOT public.is_admin_or_employee() THEN
    NEW.author_id := auth.uid();
  END IF;
  IF TG_OP = 'UPDATE' THEN
    NEW.request_id := OLD.request_id;
    NEW.created_at := OLD.created_at;
    IF NOT public.is_admin_or_employee() THEN
      NEW.author_id := OLD.author_id;
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS feature_request_comments_normalize ON public.feature_request_comments;
CREATE TRIGGER feature_request_comments_normalize
  BEFORE INSERT OR UPDATE ON public.feature_request_comments
  FOR EACH ROW
  EXECUTE FUNCTION public.feature_request_comments_normalize();

