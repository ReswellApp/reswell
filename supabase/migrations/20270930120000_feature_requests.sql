CREATE OR REPLACE FUNCTION public.feature_request_changelog_touch()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.title := trim(NEW.title);
  NEW.body := trim(NEW.body);
  IF char_length(NEW.title) < 4 OR char_length(NEW.title) > 140 THEN
    RAISE EXCEPTION 'invalid changelog title';
  END IF;
  IF char_length(NEW.body) < 10 OR char_length(NEW.body) > 5000 THEN
    RAISE EXCEPTION 'invalid changelog body';
  END IF;
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

